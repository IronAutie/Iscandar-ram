#!/usr/bin/env python3
"""gen_mass.py -- emit the kernel build's marked mass.

Reads every constant from its one home (the generated
build conf, the bridge header, the engine geometry
header, the k=4 Beam header) and writes iscandar_mass.s:
the Beam state born with the fixture runs marked, the
extent ledger born zero, the cache registry born zero,
and the arena section declared. No initial loops exist
anywhere in this design; this file is what replaces
them. Layout of record: MASS-LAYOUT.md.
"""

import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
BUILD = HERE.parent
REPO = BUILD.parent
CONF = BUILD / "constants" / "iscandar-build.conf"
BRIDGE_H = BUILD / "bridge" / "iscandar_bridge.h"
ENGINE_DIR = Path.home() / "workspace" / "iscandar" / "iscandar-engine"
K4_DIR = REPO / "c-translation" / "k4"


def read_conf(path):
    out = {}
    for line in path.read_text().splitlines():
        m = re.match(r"^(ISCANDAR_[A-Z_]+)=(\d+)$", line.strip())
        if m:
            out[m.group(1)] = int(m.group(2))
    return out


def read_define(path, name):
    for line in path.read_text().splitlines():
        m = re.match(rf"^#define\s+{name}\s+(\d+)u?\s*(/\*.*)?$", line.strip())
        if m:
            return int(m.group(1))
    raise SystemExit(f"gen_mass: {name} not found as a plain number in {path}")


def main():
    conf = read_conf(CONF)
    arity = read_define(ENGINE_DIR / "Geometry.h", "GEOMETRY_ARITY") \
        if (ENGINE_DIR / "Geometry.h").exists() else None
    if arity is None:
        # GEOMETRY_ARITY lives in whichever engine header defines it.
        for h in ENGINE_DIR.glob("*.h"):
            try:
                arity = read_define(h, "GEOMETRY_ARITY")
                break
            except SystemExit:
                continue
    if arity is None:
        raise SystemExit("gen_mass: GEOMETRY_ARITY not found in engine headers")
    max_cubes = read_define(K4_DIR / "Beam.h", "K4_BEAM_MAX_CUBES")
    fixture_ledger = read_define(BRIDGE_H, "ISCANDAR_FIXTURE_LEDGER_PAGES")
    fixture_maps = read_define(BRIDGE_H, "ISCANDAR_FIXTURE_MAPS_PAGES")
    registry_entry = read_define(BRIDGE_H, "ISCANDAR_REGISTRY_ENTRY_BYTES")

    cubes = conf["ISCANDAR_ARENA_CUBES"]
    cube_pages = conf["ISCANDAR_CUBE_PAGES"]
    arena_pages = conf["ISCANDAR_ARENA_PAGES"]
    arena_bytes = conf["ISCANDAR_ARENA_BYTES"]
    fixture_total = conf["ISCANDAR_FIXTURE_PAGES_TOTAL"]
    registry_pages = conf["ISCANDAR_REGISTRY_PAGES"]
    registry_cap = conf["ISCANDAR_REGISTRY_CAP"]

    planes = arity
    rows = arity * arity  # planes x rows-per-plane
    sectors_per_row = arity
    if rows * sectors_per_row != cube_pages:
        raise SystemExit("gen_mass: geometry does not multiply to CUBE_PAGES")
    fixture_per_cube = fixture_ledger + fixture_maps
    fixture_run = {0: fixture_per_cube + registry_pages}
    for c in range(1, cubes):
        fixture_run[c] = fixture_per_cube
    if sum(fixture_run.values()) != fixture_total:
        raise SystemExit("gen_mass: fixture runs do not sum to FIXTURE_PAGES_TOTAL")
    if arena_pages - fixture_total != conf["ISCANDAR_NET_SERVED_PAGES"]:
        raise SystemExit("gen_mass: net served arithmetic disagrees with conf")

    slot_bytes = (rows * 4) + 4 + (planes * 4) + (rows * 4) + 4
    beam_bytes = 16 + max_cubes * slot_bytes
    ledger_bytes = cubes * cube_pages * 2
    registry_bytes = registry_cap * registry_entry

    out = []
    out.append("/* iscandar_mass.s -- GENERATED by gen_mass.py from the")
    out.append(" * constants of record (iscandar-build.conf, iscandar_bridge.h,")
    out.append(" * the engine geometry, Beam.h). Do not hand-edit; regenerate.")
    out.append(f" * cardinality {cubes}, fixtures {fixture_total}, "
               f"net served {arena_pages - fixture_total}. */")
    out.append("")
    out.append('\t.section .iscandar_state,"aw",@progbits')
    out.append("\t.balign 8")
    out.append("\t.globl iscandar_mass_start")
    out.append("iscandar_mass_start:")
    out.append("\t.globl iscandar_beam")
    out.append("iscandar_beam:")
    out.append(f"\t.long {cubes}, {fixture_total}, {arena_pages}, 0"
               "  /* cardinality, count_overall, sectors_supported, lead */")
    for slot in range(max_cubes):
        run = fixture_run.get(slot, 0)
        out.append(f"\t/* CubeEngine slot {slot}: fixture run {run} */")
        if run:
            word0 = (1 << run) - 1 if run < 32 else 0xFFFFFFFF
            out.append(f"\t.long 0x{word0:08X}  /* words[0]: sectors 0..{run - 1} */")
            out.append(f"\t.fill {rows - 1},4,0  /* words[1..{rows - 1}] */")
            out.append(f"\t.long {run}  /* count_overall */")
            out.append(f"\t.long {run}  /* count_planes[0] */")
            out.append(f"\t.fill {planes - 1},4,0  /* count_planes[1..] */")
            out.append(f"\t.long {run}  /* count_rows[0] */")
            out.append(f"\t.fill {rows - 1},4,0  /* count_rows[1..] */")
            out.append(f"\t.long {run}  /* mirror count_overall */")
        else:
            out.append(f"\t.fill {slot_bytes // 4},4,0")
    out.append("\t.globl iscandar_ledger")
    out.append("iscandar_ledger:")
    out.append(f"\t.zero {ledger_bytes}  /* {cubes} cubes x {cube_pages} bins x 2 B */")
    out.append("\t.globl iscandar_registry")
    out.append("iscandar_registry:")
    out.append(f"\t.zero {registry_bytes}  /* {registry_cap} x {registry_entry} B */")
    out.append("\t.globl iscandar_mass_end")
    out.append("iscandar_mass_end:")
    out.append("")
    out.append('\t.section .iscandar_arena,"aw",@nobits')
    out.append("\t.balign 4096")
    out.append("\t.globl iscandar_arena_start")
    out.append("iscandar_arena_start:")
    out.append(f"\t.skip {arena_bytes}")
    out.append("\t.globl iscandar_arena_end")
    out.append("iscandar_arena_end:")
    out.append("")
    out.append('\t.section .note.GNU-stack,"",@progbits')
    out.append("")

    target = HERE / "iscandar_mass.s"
    target.write_text("\n".join(out))
    print(f"gen_mass: wrote {target}")
    print(f"  beam {beam_bytes} B, ledger {ledger_bytes} B, "
          f"registry {registry_bytes} B, mass {beam_bytes + ledger_bytes + registry_bytes} B")
    print(f"  arena section {arena_bytes} B declared")
    return 0


if __name__ == "__main__":
    sys.exit(main())
